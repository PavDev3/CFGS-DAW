package ArrayAvanzada;

public class Asignatura {
	// Atributos
	private String nombre;
	
	// Constructor
	public Asignatura(String nombre) {
		this.nombre = nombre;
	}
	
	// Getters y Setters
	
	public String getNombre() {
		return nombre;
	}
	
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}

}
